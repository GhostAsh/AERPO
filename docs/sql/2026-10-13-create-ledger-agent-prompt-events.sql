select
  to_regclass('public.erp_ledger') as erp_ledger_table,
  to_regclass('public.agent_telemetry') as agent_telemetry_table,
  to_regclass('public.ledger_agent_prompt_events') as prompt_events_table;

-- ---------------------------------------------------------------------------
-- Migration body
-- ---------------------------------------------------------------------------

create table if not exists public.ledger_agent_prompt_events (
  id bigint generated by default as identity primary key,
  ledger_id bigint not null references public.erp_ledger(id) on delete cascade,
  event_type text not null,
  human_prompt text,
  agent_response text,
  status text not null default 'queued',
  created_at timestamptz not null default now(),
  completed_at timestamptz,
  created_by uuid,
  telemetry_id bigint references public.agent_telemetry(id) on delete set null,
  error_message text,

  constraint ledger_agent_prompt_events_event_type_check
    check (
      event_type in (
        'prompt_rerun',
        'evidence_request',
        'human_approval',
        'human_rejection',
        'agent_response'
      )
    ),

  constraint ledger_agent_prompt_events_status_check
    check (
      status in (
        'queued',
        'thinking',
        'completed',
        'failed',
        'protocol_blocked'
      )
    ),

  constraint ledger_agent_prompt_events_completed_at_check
    check (
      completed_at is null
      or completed_at >= created_at
    )
);

create index if not exists ledger_agent_prompt_events_ledger_created_idx
  on public.ledger_agent_prompt_events (ledger_id, created_at desc);

create index if not exists ledger_agent_prompt_events_status_created_idx
  on public.ledger_agent_prompt_events (status, created_at desc);

create index if not exists ledger_agent_prompt_events_telemetry_idx
  on public.ledger_agent_prompt_events (telemetry_id)
  where telemetry_id is not null;

alter table public.ledger_agent_prompt_events enable row level security;

grant usage on schema public to service_role;
grant select, insert, update on public.ledger_agent_prompt_events to service_role;
grant usage, select on sequence public.ledger_agent_prompt_events_id_seq to service_role;

comment on table public.ledger_agent_prompt_events is
  'Append-only ledger prompt events for human prompts, agent responses, and protocol outcomes.';

comment on column public.ledger_agent_prompt_events.ledger_id is
  'Foreign key to public.erp_ledger.id.';

comment on column public.ledger_agent_prompt_events.telemetry_id is
  'Optional foreign key to public.agent_telemetry.id for the agent run that answered the prompt.';

comment on column public.ledger_agent_prompt_events.status is
  'queued, thinking, completed, failed, or protocol_blocked.';

comment on column public.ledger_agent_prompt_events.event_type is
  'prompt_rerun, evidence_request, human_approval, human_rejection, or agent_response.';

