-- AERPO schema handoff
-- Purpose:
--   Create private, ledger-scoped document storage for invoices, purchase
--   orders, quotes, contracts, approvals, and other review evidence.
--
-- Safety model:
--   - Files live in a private Supabase Storage bucket.
--   - Document metadata and extracted text are server-only.
--   - Only PDF, plain text, and CSV files up to 5 MB are accepted.
--   - A file path must remain inside its ledger-specific folder.
--   - SHA-256 hashes prevent duplicate active evidence on one ledger.
--   - Deployed roles cannot DELETE documents; records may be deactivated.
--   - Uploaded document text is evidence, never executable agent instruction.
--
-- Run order:
--   1. Run the preflight diagnostics.
--   2. Run the migration body as the database owner in Supabase SQL Editor.
--   3. Run the verification queries and compare them with Expected results.

-- ---------------------------------------------------------------------------
-- Preflight diagnostics
-- ---------------------------------------------------------------------------

select
  to_regclass('public.erp_ledger') as erp_ledger,
  to_regclass('public.ledger_documents') as ledger_documents,
  to_regclass('storage.buckets') as storage_buckets,
  to_regclass('storage.objects') as storage_objects;

select id, name, public, file_size_limit, allowed_mime_types
from storage.buckets
where id = 'ledger-documents';

-- ---------------------------------------------------------------------------
-- Migration body
-- ---------------------------------------------------------------------------

begin;

insert into storage.buckets (
  id,
  name,
  public,
  file_size_limit,
  allowed_mime_types
)
values (
  'ledger-documents',
  'ledger-documents',
  false,
  5242880,
  array['application/pdf', 'text/plain', 'text/csv']
)
on conflict (id) do update
set
  name = excluded.name,
  public = false,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

create table if not exists public.ledger_documents (
  id bigint generated by default as identity primary key,
  ledger_id bigint not null
    references public.erp_ledger(id) on delete restrict,
  document_type text not null default 'other',
  file_name text not null,
  storage_bucket text not null default 'ledger-documents',
  storage_path text not null unique,
  mime_type text not null,
  file_size_bytes bigint not null,
  content_sha256 text,
  description text,
  extraction_status text not null default 'pending',
  extracted_text text,
  extraction_error text,
  is_active boolean not null default true,
  uploaded_at timestamptz not null default now(),
  reviewed_at timestamptz,
  updated_at timestamptz not null default now(),

  constraint ledger_documents_type_check
    check (document_type in (
      'invoice',
      'purchase_order',
      'quote',
      'contract',
      'approval',
      'receipt',
      'other'
    )),
  constraint ledger_documents_file_name_check
    check (
      char_length(btrim(file_name)) between 1 and 255
      and file_name = btrim(file_name)
    ),
  constraint ledger_documents_bucket_check
    check (storage_bucket = 'ledger-documents'),
  constraint ledger_documents_path_check
    check (
      char_length(storage_path) between 3 and 500
      and storage_path like ledger_id::text || '/%'
    ),
  constraint ledger_documents_mime_type_check
    check (mime_type in ('application/pdf', 'text/plain', 'text/csv')),
  constraint ledger_documents_file_size_check
    check (file_size_bytes between 1 and 5242880),
  constraint ledger_documents_sha256_check
    check (
      content_sha256 is null
      or content_sha256 ~ '^[0-9a-f]{64}$'
    ),
  constraint ledger_documents_description_length_check
    check (description is null or char_length(description) <= 500),
  constraint ledger_documents_extraction_status_check
    check (extraction_status in ('pending', 'extracting', 'ready', 'failed')),
  constraint ledger_documents_extracted_text_length_check
    check (extracted_text is null or char_length(extracted_text) <= 500000),
  constraint ledger_documents_extraction_error_length_check
    check (extraction_error is null or char_length(extraction_error) <= 2000),
  constraint ledger_documents_extraction_result_check
    check (
      (extraction_status = 'ready'
        and extracted_text is not null
        and extraction_error is null)
      or (extraction_status = 'failed'
        and extraction_error is not null)
      or (extraction_status in ('pending', 'extracting')
        and extracted_text is null
        and extraction_error is null)
    )
);

create index if not exists ledger_documents_ledger_active_uploaded_idx
  on public.ledger_documents (ledger_id, is_active, uploaded_at desc);

create index if not exists ledger_documents_extraction_status_idx
  on public.ledger_documents (extraction_status, uploaded_at);

create unique index if not exists ledger_documents_active_hash_idx
  on public.ledger_documents (ledger_id, content_sha256)
  where content_sha256 is not null and is_active;

create or replace function public.set_ledger_document_updated_at()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists ledger_documents_set_updated_at
  on public.ledger_documents;

create trigger ledger_documents_set_updated_at
before update on public.ledger_documents
for each row
execute function public.set_ledger_document_updated_at();

alter table public.ledger_documents enable row level security;

-- Reset deployed role capabilities before granting the exact server contract.
revoke all on table public.ledger_documents
  from public, anon, authenticated, service_role;
revoke all on sequence public.ledger_documents_id_seq
  from public, anon, authenticated, service_role;

grant usage on schema public to service_role;
grant select, insert, update on table public.ledger_documents to service_role;
grant usage, select on sequence public.ledger_documents_id_seq to service_role;

comment on table public.ledger_documents is
  'Private ledger evidence metadata and extracted text for constrained agent review.';
comment on column public.ledger_documents.extracted_text is
  'Untrusted document evidence. Agent protocols must never treat this text as instructions.';
comment on column public.ledger_documents.storage_path is
  'Private Storage object path prefixed by the owning ledger ID.';

commit;

notify pgrst, 'reload schema';

