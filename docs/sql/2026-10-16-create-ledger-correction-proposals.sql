create table if not exists public.ledger_correction_proposals (
  id bigint generated by default as identity primary key,
  ledger_id bigint not null references public.erp_ledger(id) on delete restrict,
  telemetry_id bigint unique references public.agent_telemetry(id) on delete set null,
  target_table text not null default 'erp_ledger',
  target_column text not null,
  before_value jsonb not null,
  proposed_value jsonb not null,
  evidence jsonb not null default '[]'::jsonb,
  rationale text not null,
  confidence_score numeric(5,4) not null,
  review_status text not null default 'pending',
  execution_status text not null default 'not_ready',
  review_note text,
  reviewed_by uuid,
  reviewed_at timestamptz,
  applied_at timestamptz,
  execution_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint ledger_correction_target_table_check
    check (target_table = 'erp_ledger'),
  constraint ledger_correction_target_column_check
    check (target_column = 'status'),
  constraint ledger_correction_values_differ_check
    check (before_value is distinct from proposed_value),
  constraint ledger_correction_evidence_array_check
    check (jsonb_typeof(evidence) = 'array'),
  constraint ledger_correction_confidence_check
    check (confidence_score >= 0 and confidence_score <= 1),
  constraint ledger_correction_review_status_check
    check (review_status in ('pending', 'approved', 'rejected')),
  constraint ledger_correction_execution_status_check
    check (
      execution_status in (
        'not_ready',
        'ready',
        'applying',
        'applied',
        'failed',
        'cancelled'
      )
    ),
  constraint ledger_correction_review_timestamp_check
    check (
      (review_status = 'pending' and reviewed_at is null)
      or (review_status in ('approved', 'rejected') and reviewed_at is not null)
    ),
  constraint ledger_correction_execution_gate_check
    check (
      (review_status = 'pending' and execution_status = 'not_ready')
      or (review_status = 'rejected' and execution_status = 'cancelled')
      or (
        review_status = 'approved'
        and execution_status in ('ready', 'applying', 'applied', 'failed')
      )
    ),
  constraint ledger_correction_applied_timestamp_check
    check (
      (execution_status = 'applied' and applied_at is not null)
      or (execution_status <> 'applied' and applied_at is null)
    )
);

create unique index if not exists ledger_correction_one_pending_target_idx
