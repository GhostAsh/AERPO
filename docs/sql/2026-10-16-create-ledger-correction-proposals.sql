-- AERPO schema handoff
-- Purpose:
--   Create an auditable correction proposal queue that separates an agent's
--   suggested change, a human decision, and constrained database execution.
--
-- Safety model:
--   - The agent may propose a change but cannot approve it.
--   - Human approval changes review_status to approved and execution_status
--     to ready; it does not mutate erp_ledger.
--   - apply_ledger_correction is the only executor in this migration.
--   - The executor currently permits public.erp_ledger.status only.
--   - The original value must still match before execution, preventing a
--     stale proposal from overwriting newer work.
--
-- Run order:
--   1. Run preflight diagnostics.
--   2. Run the migration body as a database owner in Supabase SQL Editor.
--   3. Run verification queries.
--
-- Application access:
--   Server routes and the Python optimizer use service_role. No anon or
--   authenticated browser policy is created.

-- ---------------------------------------------------------------------------
-- Preflight diagnostics
-- ---------------------------------------------------------------------------

select
  to_regclass('public.erp_ledger') as erp_ledger_table,
  to_regclass('public.agent_telemetry') as agent_telemetry_table,
  to_regclass('public.ledger_agent_prompt_events') as prompt_events_table,
