create or replace function public.apply_ledger_correction(
  p_correction_id bigint
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  correction public.ledger_correction_proposals%rowtype;
  current_status text;
  next_status text;
begin
  select *
  into correction
  from public.ledger_correction_proposals
  where id = p_correction_id
  for update;

  if not found then
    return jsonb_build_object(
      'ok', false,
      'code', 'CORRECTION_NOT_FOUND',
      'message', 'Correction proposal does not exist.'
    );
  end if;

  if correction.review_status <> 'approved'
     or correction.execution_status not in ('ready', 'failed') then
    return jsonb_build_object(
      'ok', false,
      'code', 'CORRECTION_NOT_READY',
      'message', 'Correction must be approved and ready before execution.'
    );
  end if;

  update public.ledger_correction_proposals
  set execution_status = 'applying', execution_error = null
  where id = correction.id;

  if correction.target_table <> 'erp_ledger'
     or correction.target_column <> 'status' then
    update public.ledger_correction_proposals
    set
      execution_status = 'failed',
      execution_error = 'Protocol blocked a non-allowlisted target.'
    where id = correction.id;

    return jsonb_build_object(
      'ok', false,
      'code', 'TARGET_NOT_ALLOWLISTED',
      'message', 'Protocol blocked a non-allowlisted target.'
    );
  end if;

  if jsonb_typeof(correction.proposed_value) <> 'string' then
    update public.ledger_correction_proposals
    set
      execution_status = 'failed',
      execution_error = 'Proposed status must be a JSON string.'
    where id = correction.id;

    return jsonb_build_object(
      'ok', false,
      'code', 'INVALID_PROPOSED_VALUE',
      'message', 'Proposed status must be a string.'
    );
  end if;

  next_status := correction.proposed_value #>> '{}';

  if next_status not in ('pending', 'review', 'approved', 'duplicate') then
    update public.ledger_correction_proposals
    set
      execution_status = 'failed',
      execution_error = 'Proposed status is outside the allowlist.'
    where id = correction.id;

    return jsonb_build_object(
      'ok', false,
      'code', 'VALUE_NOT_ALLOWLISTED',
      'message', 'Proposed status is outside the allowlist.'
    );
  end if;

  select status
  into current_status
  from public.erp_ledger
  where id = correction.ledger_id
  for update;

  if not found then
    update public.ledger_correction_proposals
    set
      execution_status = 'failed',
      execution_error = 'The linked ledger no longer exists.'
    where id = correction.id;

    return jsonb_build_object(
      'ok', false,
      'code', 'LEDGER_NOT_FOUND',
      'message', 'The linked ledger no longer exists.'
    );
  end if;

  if coalesce(to_jsonb(current_status), 'null'::jsonb)
     is distinct from correction.before_value then
    update public.ledger_correction_proposals
    set
      execution_status = 'failed',
      execution_error = 'Ledger changed after this correction was proposed.'
    where id = correction.id;

    return jsonb_build_object(
      'ok', false,
      'code', 'STALE_BEFORE_VALUE',
      'message', 'Ledger changed after this correction was proposed.'
    );
  end if;

  update public.erp_ledger
  set status = next_status
  where id = correction.ledger_id;

  update public.ledger_correction_proposals
  set
    execution_status = 'applied',
    applied_at = now(),
    execution_error = null
  where id = correction.id;

  return jsonb_build_object(
    'ok', true,
    'code', 'CORRECTION_APPLIED',
    'correction_id', correction.id,
    'ledger_id', correction.ledger_id,
    'column', correction.target_column,
    'before', correction.before_value,
    'after', correction.proposed_value
  );
exception
  when others then
    update public.ledger_correction_proposals
    set
      execution_status = 'failed',
      execution_error = left(sqlerrm, 1000)
    where id = p_correction_id;

    return jsonb_build_object(
      'ok', false,
      'code', 'EXECUTION_FAILED',
      'message', left(sqlerrm, 1000)
    );
end;
$$;

create or replace function public.review_ledger_correction(
  p_correction_id bigint,
  p_decision text,
  p_review_note text default null,
  p_reviewed_by uuid default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  correction public.ledger_correction_proposals%rowtype;
  decision_event_id bigint;
  next_review_status text;
  next_execution_status text;
  next_event_type text;
  decision_message text;
begin
  if p_decision not in ('approved', 'rejected') then
    return jsonb_build_object(
      'ok', false,
      'code', 'INVALID_REVIEW_DECISION',
      'message', 'Decision must be approved or rejected.'
    );
  end if;

  select *
  into correction
  from public.ledger_correction_proposals
  where id = p_correction_id
  for update;

  if not found then
    return jsonb_build_object(
      'ok', false,
      'code', 'CORRECTION_NOT_FOUND',
      'message', 'Correction proposal does not exist.'
    );
  end if;

  if correction.execution_status in ('applying', 'applied') then
    return jsonb_build_object(
      'ok', false,
      'code', 'CORRECTION_ALREADY_EXECUTED',
      'message', 'An applying or applied correction cannot be reviewed again.'
    );
  end if;

  if p_decision = 'approved' then
    next_review_status := 'approved';
    next_execution_status := 'ready';
    next_event_type := 'human_approval';
    decision_message :=
      'Correction approved and ready for constrained execution. No ledger mutation was performed.';
  else
    next_review_status := 'rejected';
    next_execution_status := 'cancelled';
    next_event_type := 'human_rejection';
    decision_message :=
      'Correction rejected and closed. No ledger mutation was performed.';
  end if;

  update public.ledger_correction_proposals
  set
    review_status = next_review_status,
    execution_status = next_execution_status,
    review_note = nullif(btrim(p_review_note), ''),
    reviewed_by = p_reviewed_by,
    reviewed_at = now(),
    applied_at = null,
    execution_error = null
  where id = correction.id;

  insert into public.ledger_agent_prompt_events (
    ledger_id,
    event_type,
    human_prompt,
    agent_response,
    status,
    completed_at,
    created_by,
    telemetry_id
  ) values (
    correction.ledger_id,
    next_event_type,
    format(
      'Correction candidate #%s %s by human review.%s',
      correction.telemetry_id,
      next_review_status,
      case
        when nullif(btrim(p_review_note), '') is null then ''
        else ' Note: ' || btrim(p_review_note)
      end
    ),
    decision_message,
    'completed',
    now(),
    p_reviewed_by,
    correction.telemetry_id
  )
  returning id into decision_event_id;

  return jsonb_build_object(
    'ok', true,
    'code', 'CORRECTION_REVIEWED',
    'correction_id', correction.id,
    'decision_event_id', decision_event_id,
    'review_status', next_review_status,
    'execution_status', next_execution_status,
    'reviewed_at', now()
  );
end;
$$;

