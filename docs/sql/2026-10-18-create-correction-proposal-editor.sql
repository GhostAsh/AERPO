create table if not exists public.ledger_correction_proposal_edits (
  id bigint generated by default as identity primary key,
  correction_id bigint not null
    references public.ledger_correction_proposals(id) on delete restrict,
  before_proposed_value jsonb not null,
  after_proposed_value jsonb not null,
  edit_note text,
  edited_by uuid,
  created_at timestamptz not null default now(),

  constraint ledger_correction_edit_values_differ_check
    check (before_proposed_value is distinct from after_proposed_value),
  constraint ledger_correction_edit_note_length_check
    check (edit_note is null or char_length(edit_note) <= 500)
);

create index if not exists ledger_correction_edits_correction_created_idx
  on public.ledger_correction_proposal_edits (correction_id, created_at desc);

create or replace function public.edit_ledger_correction_proposal(
  p_correction_id bigint,
  p_proposed_status text,
  p_edit_note text default null,
  p_edited_by uuid default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  correction public.ledger_correction_proposals%rowtype;
  next_value jsonb;
  normalized_note text;
  edit_id bigint;
begin
  normalized_note := nullif(btrim(p_edit_note), '');

  if normalized_note is not null and char_length(normalized_note) > 500 then
    return jsonb_build_object(
      'ok', false,
      'code', 'EDIT_NOTE_TOO_LONG',
      'message', 'Edit note cannot exceed 500 characters.'
    );
  end if;

  if p_proposed_status not in ('pending', 'review', 'approved', 'duplicate') then
    return jsonb_build_object(
      'ok', false,
      'code', 'VALUE_NOT_ALLOWLISTED',
      'message', 'Proposed status is outside the correction allowlist.'
    );
  end if;

  select *
  into correction
  from public.ledger_correction_proposals
  where id = p_correction_id
  for update;

  if not found then
    return jsonb_build_object(
      'ok', false,
      'code', 'CORRECTION_NOT_FOUND',
      'message', 'Correction proposal does not exist.'
    );
  end if;

  if correction.review_status <> 'pending'
     or correction.execution_status <> 'not_ready' then
    return jsonb_build_object(
      'ok', false,
      'code', 'CORRECTION_EDIT_LOCKED',
      'message', 'Only pending, unexecuted corrections may be edited.'
    );
  end if;

  if correction.target_table <> 'erp_ledger'
     or correction.target_column <> 'status' then
    return jsonb_build_object(
      'ok', false,
      'code', 'TARGET_NOT_ALLOWLISTED',
      'message', 'Protocol blocked an edit to a non-allowlisted target.'
    );
  end if;

  next_value := to_jsonb(p_proposed_status);

  if next_value is not distinct from correction.before_value then
    return jsonb_build_object(
      'ok', false,
      'code', 'CORRECTION_REQUIRES_CHANGED_VALUE',
      'message', 'The proposed status must differ from the captured ledger status.'
    );
  end if;

  if next_value is not distinct from correction.proposed_value then
    return jsonb_build_object(
      'ok', true,
      'code', 'CORRECTION_EDIT_UNCHANGED',
      'correction_id', correction.id,
      'proposed_value', correction.proposed_value,
      'review_note', correction.review_note,
      'updated_at', correction.updated_at
    );
  end if;

  insert into public.ledger_correction_proposal_edits (
    correction_id,
    before_proposed_value,
    after_proposed_value,
    edit_note,
    edited_by
  ) values (
    correction.id,
    correction.proposed_value,
    next_value,
    normalized_note,
    p_edited_by
  )
  returning id into edit_id;

  update public.ledger_correction_proposals
  set
    proposed_value = next_value,
    review_note = coalesce(normalized_note, review_note)
  where id = correction.id
  returning * into correction;

  return jsonb_build_object(
    'ok', true,
    'code', 'CORRECTION_EDITED',
    'correction_id', correction.id,
    'edit_id', edit_id,
    'proposed_value', correction.proposed_value,
    'review_note', correction.review_note,
    'updated_at', correction.updated_at
  );
end;
$$;

