-- AERPO schema handoff
-- Purpose:
--   Allow a human to amend a pending ledger status correction before review,
--   while preserving every proposal edit as an immutable audit record.
--
-- Safety model:
--   - Only pending, not_ready proposals may be edited.
--   - Only public.erp_ledger.status remains editable.
--   - Proposed values remain limited to the existing status allowlist.
--   - A proposed value must differ from the ledger value captured at proposal time.
--   - Editing does not approve or apply a correction.
--   - Only service_role may execute the edit function.
--
-- Run order:
--   1. Run preflight diagnostics.
--   2. Run the migration body as a database owner in Supabase SQL Editor.
--   3. Run verification queries.

-- ---------------------------------------------------------------------------
-- Preflight diagnostics
-- ---------------------------------------------------------------------------

select
